/* Calling PL/OCaml functions from SQL and vice versa should not lose context.
 */
CREATE OR REPLACE FUNCTION ocaml_traceback() RETURNS void AS $$
let rec first () = second (); ()
and second () = third (); ()
and third () = ignore (PL.execute "select sql_error()")
in
first ();
()
$$ LANGUAGE plocamlu;

