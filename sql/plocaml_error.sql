/* a typo
 */
CREATE FUNCTION invalid_type_uncaught(a text) RETURNS text
	AS $$
if not (Hashtbl.mem sd "plan") then
  PL.set sd "plan" (PL.prepare "SELECT fname FROM users WHERE lname = $1" [|"test"|]);
let rv = PL.execute_plan (PL.get sd "plan") [| a |] in
if Array.length rv.rows > 0 then List.assoc "fname" rv.rows.(0)
else PL.Null
$$ LANGUAGE plocamlu;

SELECT invalid_type_uncaught('rick');


/* for what it's worth catch the exception generated by
 * the typo, and return None
 */
CREATE FUNCTION invalid_type_caught(a text) RETURNS text
	AS $$
if not (Hashtbl.mem sd "plan") then
  (try
    PL.set sd "plan" (PL.prepare "SELECT fname FROM users WHERE lname = $1" [|"test"|])
  with Failure ex ->
    PL.notice ex);
if not (Hashtbl.mem sd "plan") then PL.Null
else
  let rv = PL.execute_plan (PL.get sd "plan") [| a |] in
  if Array.length rv.rows > 0 then List.assoc "fname" rv.rows.(0)
  else PL.Null
$$ LANGUAGE plocamlu;

SELECT invalid_type_caught('rick');


/* for what it's worth catch the exception generated by
 * the typo, and reraise it as a plain error
 */
CREATE FUNCTION invalid_type_reraised(a text) RETURNS text
	AS $$
if not (Hashtbl.mem sd "plan") then
  (try
    PL.set sd "plan" (PL.prepare "SELECT fname FROM users WHERE lname = $1" [|"test"|])
  with Failure ex ->
    PL.error ex);
let rv = PL.execute_plan (PL.get sd "plan") [| a |] in
if Array.length rv.rows > 0 then List.assoc "fname" rv.rows.(0)
else PL.Null
$$ LANGUAGE plocamlu;

SELECT invalid_type_reraised('rick');


