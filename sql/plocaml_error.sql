/* test error logged with an underlying exception that includes a detail
 * string (bug #18070).
 */
CREATE FUNCTION ocaml_error_detail() RETURNS SETOF text AS $$
  let plan = PL.prepare "SELECT to_date('xy', 'DD') d" [||] in
  let cur = PL.cursor_plan plan [||] in
  let rec acc xs =
    let batch = PL.fetch cur 1 in
    if batch.nrows = 0 then List.rev xs
    else acc (List.assoc "d" batch.rows.(0) :: xs)
  in
  PL.Array (Array.of_list (acc []))
$$ LANGUAGE plocamlu;

SELECT ocaml_error_detail();
